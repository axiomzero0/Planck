/// Where the System V ABI delivers parameter `index`. Shared by the prologue
/// spills and the `Arg` instruction so the two can never disagree.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum ArgLoc {
    IntReg(usize),
    XmmReg(usize),
    Stack(usize),
}

const INT_ARG_REGS: [&str; 6] = ["%rdi", "%rsi", "%rdx", "%rcx", "%r8", "%r9"];

// CEP:WHAT: Handles the Classifies each parameter into its System V ABI location per the design and the file header contract. step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn abi_param_locations(func: &IrFunc) -> Vec<ArgLoc> {
    let mut locs = Vec::with_capacity(func.params.len());
    let mut int_idx = 0usize;
    let mut xmm_idx = 0usize;
    let mut stack_idx = 0usize;
    for slot in &func.params {
        let ty = &func.slots[slot.0 as usize].ty;
        let loc = match ty {
            Ty::F32 | Ty::F64 => {
                let loc = ArgLoc::XmmReg(xmm_idx);
                xmm_idx += 1;
                loc
            }
            _ => {
                // Scalars and aggregate pointers share the integer register file.
                if int_idx < INT_ARG_REGS.len() {
                    let loc = ArgLoc::IntReg(int_idx);
                    int_idx += 1;
                    loc
                } else {
                    let loc = ArgLoc::Stack(stack_idx);
                    stack_idx += 1;
                    loc
                }
            }
        };
        locs.push(loc);
    }
    locs
}

// CEP:WHAT: Handles the Spills non-promoted parameters from their ABI registers into frame slots per the design and the file header contract. step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_param_spills(em: &mut FuncEmitter, promoted: &std::collections::BTreeSet<u32>) {
    let locs = abi_param_locations(em.func);
    for (param_idx, slot) in em.func.params.iter().enumerate() {
        // Promoted parameters are read by their Arg instruction in the entry
        // block; spilling them here would be dead work into a dead slot.
        if promoted.contains(&(param_idx as u32)) {
            continue;
        }
        let ty = &em.func.slots[slot.0 as usize].ty;
        let loc = locs[param_idx];
        match (ty, loc) {
            (Ty::F32 | Ty::F64, ArgLoc::XmmReg(xmm)) => {
                let mem = em.slot_mem(*slot, 0);
                let suffix = if matches!(ty, Ty::F32) { "ss" } else { "sd" };
                em.w(&format!("    mov{} %xmm{}, {}", suffix, xmm, mem));
            }
            (Ty::Struct(_) | Ty::Enum(_) | Ty::Array(_, _), loc) => {
                // Aggregates arrive as pointers to caller copies: memcpy into the slot.
                match loc {
                    ArgLoc::IntReg(reg_idx) => {
                        em.w(&format!("    movq {}, %rsi", INT_ARG_REGS[reg_idx]));
                    }
                    ArgLoc::Stack(stack_idx) => {
                        let src = format!("{}(%rbp)", 16 + 8 * stack_idx);
                        em.w(&format!("    movq {}, %rsi", src));
                    }
                    ArgLoc::XmmReg(_) => {
                        // Rejected at the language level (PLK-026): floats never
                        // exhaust the eight XMM registers in v0.1.
                        em.w("    ud2 # float aggregate parameter (unreachable)");
                    }
                }
                let mem = em.slot_mem(*slot, 0);
                em.w(&format!("    lea {}, %rdi", mem));
                let size = em.tables_size_of(ty);
                em.w(&format!("    movq ${}, %rcx", size));
                em.w("    rep movsb");
            }
            (_, ArgLoc::IntReg(reg_idx)) => {
                // Spill with the parameter's own width: the frame packs narrow
                // slots adjacently, so an 8-byte store into a 4-byte slot
                // would corrupt the neighboring slot's bytes.
                let mem = em.slot_mem(*slot, 0);
                // store_insn writes from %rax; bring the ABI register there first.
                em.w(&format!("    movq {}, %rax", INT_ARG_REGS[reg_idx]));
                em.w(&format!("    {}", store_insn(ty, &mem)));
            }
            (_, ArgLoc::Stack(stack_idx)) => {
                let mem = em.slot_mem(*slot, 0);
                let src = format!("{}(%rbp)", 16 + 8 * stack_idx);
                em.w(&format!("    {}", load_insn(ty, &src)));
                em.w(&format!("    {}", store_insn(ty, &mem)));
            }
            (_, ArgLoc::XmmReg(_)) => {
                // Floats always take the XMM arm above; a non-float can never
                // be classified into XMM.
                em.w("    ud2 # unexpected XMM parameter class (unreachable)");
            }
        }
    }
}

// CEP:WHAT: Handles the emit return step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_return(em: &mut FuncEmitter, value: Option<&planck_ir::Vreg>) {
    match &em.func.ret {
        Ty::Unit => {}
        Ty::F32 | Ty::F64 => {
            if let Some(vreg) = value {
                let mem = em.vreg_mem(vreg.0);
                let suffix = if matches!(em.func.ret, Ty::F32) {
                    "ss"
                } else {
                    "sd"
                };
                em.w(&format!("    mov{} {}, %xmm0", suffix, mem));
            }
        }
        ret if ret.scalar_size().is_some() => {
            if let Some(vreg) = value {
                em.load_vreg(vreg.0, ret);
            }
        }
        // Aggregate: copy the sret buffer to the caller's pointer; return the pointer in rax.
        _ => {
            if let (Some(_sret_slot), Some(save_off)) =
                (em.func.sret_slot, em.frame.sret_save_offset)
            {
                em.w(&format!("    movq -{}(%rbp), %rdi", save_off));
                let sret_slot = em.func.sret_slot.expect("checked above");
                let src = em.slot_mem(sret_slot, 0);
                em.w(&format!("    lea {}, %rsi", src));
                let size = em.func.slots[sret_slot.0 as usize].size;
                em.w(&format!("    movq ${}, %rcx", size));
                em.w("    rep movsb");
                em.w(&format!("    movq -{}(%rbp), %rax", save_off));
            }
        }
    }
    em.w("    leave");
    em.w("    ret");
}

// CEP:WHAT: Handles the emit inst step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_inst(em: &mut FuncEmitter, inst: &Inst) {
    match inst {
        Inst::Const { dst, value } => emit_const(em, *dst, value),
        Inst::Bin {
            op,
            dst,
            a,
            b,
            ty,
            checked,
        } => emit_bin(em, *op, *dst, *a, *b, ty, *checked),
        Inst::Un {
            op,
            dst,
            a,
            ty,
            checked,
        } => emit_unary(em, *op, *dst, *a, ty, *checked),
        Inst::Cast { dst, src, from, to } => emit_cast(em, *dst, *src, from, to),
        Inst::LoadSlot { dst, slot, ty } => {
            let mem = em.slot_mem(*slot, 0);
            em.w(&format!("    {}", load_insn(ty, &mem)));
            em.store_vreg(dst.0, ty);
        }
        Inst::LoadField {
            dst,
            slot,
            offset,
            ty,
        } => {
            let mem = em.slot_mem(*slot, *offset);
            em.w(&format!("    {}", load_insn(ty, &mem)));
            em.store_vreg(dst.0, ty);
        }
        Inst::StoreSlot { slot, src, ty } => {
            em.load_vreg(src.0, ty);
            let mem = em.slot_mem(*slot, 0);
            em.w(&format!("    {}", store_insn(ty, &mem)));
        }
        Inst::StoreField {
            slot,
            offset,
            src,
            ty,
        } => {
            em.load_vreg(src.0, ty);
            let mem = em.slot_mem(*slot, *offset);
            em.w(&format!("    {}", store_insn(ty, &mem)));
        }
        Inst::AddrSlot {
            dst,
            slot,
            pointee,
            mutable,
        } => {
            let _ = (pointee, mutable);
            let mem = em.slot_mem(*slot, 0);
            em.w(&format!("    lea {}, %rax", mem));
            em.store_vreg(dst.0, &Ty::U64);
        }
        Inst::AddrOffset {
            dst,
            base,
            offset,
            pointee,
        } => {
            em.load_vreg(base.0, &Ty::U64);
            em.w("    movq %rax, %rcx");
            em.load_vreg(offset.0, &Ty::U64);
            em.w("    addq %rcx, %rax");
            let _ = pointee;
            em.store_vreg(dst.0, &Ty::U64);
        }
        Inst::LoadIndirect {
            dst,
            addr,
            offset,
            ty,
        } => {
            em.load_vreg(addr.0, &Ty::U64);
            let mem = format!("{}(%rax)", offset);
            em.w(&format!("    {}", load_insn(ty, &mem)));
            em.store_vreg(dst.0, ty);
        }
        Inst::StoreIndirect {
            addr,
            offset,
            src,
            ty,
        } => {
            em.load_vreg(addr.0, &Ty::U64);
            em.w("    movq %rax, %rcx");
            // Aggregate pointees travel by address: memcpy the pointee bytes
            // from the source address into addr+offset (address-value
            // convention). The source vreg holds the source address.
            let pointee = match ty {
                Ty::Ref(inner, _) => Some(inner.as_ref().clone()),
                _ => None,
            };
            match pointee {
                // Structs and enums have no scalar size; Unit never stores.
                Some(pointee_ty)
                    if pointee_ty.scalar_size().is_none() && !matches!(pointee_ty, Ty::Unit) =>
                {
                    let size = em.tables_size_of(&pointee_ty);
                    em.load_vreg(src.0, &Ty::U64);
                    em.w("    movq %rax, %rsi");
                    em.w(&format!("    lea {}(%rcx), %rdi", offset));
                    em.w(&format!("    movq ${}, %rcx", size));
                    em.w("    rep movsb");
                }
                _ => {
                    em.load_vreg(src.0, ty);
                    let store = store_insn(ty, &format!("{}(%rcx)", offset));
                    em.w(&format!("    {}", store));
                }
            }
        }
        Inst::StoreStructFromAddr {
            dst_slot,
            src_addr,
            ty,
        } => {
            let size = em.tables_size_of(ty);
            em.load_vreg(src_addr.0, &Ty::U64);
            em.w("    movq %rax, %rsi");
            let dst_mem = em.slot_mem(*dst_slot, 0);
            em.w(&format!("    lea {}, %rdi", dst_mem));
            em.w(&format!("    movq ${}, %rcx", size));
            em.w("    rep movsb");
            // rax still holds src_addr; keep forwarding.
        }
        Inst::Call {
            dst,
            sret,
            func: callee,
            args,
            ret,
        } => {
            emit_call(em, *dst, *sret, *callee, args, ret);
        }
        Inst::TrapIf { cond, trap } => {
            em.load_vreg(cond.0, &Ty::Bool);
            em.w("    testb $1, %al");
            em.w(&format!("    jne {}_{}", trap_label(*trap), em.fn_index));
        }
        Inst::Trap { trap } => {
            em.w(&format!("    jmp {}_{}", trap_label(*trap), em.fn_index));
        }
        Inst::Comment { .. } => {}
        Inst::Copy { dst, src, ty } => {
            // Load src into %rax (or %xmm0), store to dst: the frame-resident
            // model makes a copy a load followed by a store, with rax
            // forwarding eliding the load when src was just produced.
            em.load_vreg(src.0, ty);
            em.store_vreg(dst.0, ty);
        }
        Inst::Arg { dst, index, ty } => {
            // Reads the ABI location of parameter `index`. The verifier
            // restricts Arg to the entry-block prefix, so no call can have
            // clobbered the register yet.
            let locs = abi_param_locations(em.func);
            let loc = locs
                .get(*index as usize)
                .copied()
                .unwrap_or(ArgLoc::Stack(0));
            match loc {
                ArgLoc::IntReg(reg_idx) => {
                    em.w(&format!("    movq {}, %rax", INT_ARG_REGS[reg_idx]));
                    em.store_vreg(dst.0, ty);
                }
                ArgLoc::XmmReg(xmm) => {
                    let suffix = if matches!(ty, Ty::F32) { "ss" } else { "sd" };
                    em.w(&format!("    mov{} %xmm{}, %xmm0", suffix, xmm));
                    em.store_vreg(dst.0, ty);
                }
                ArgLoc::Stack(stack_idx) => {
                    let src = format!("{}(%rbp)", 16 + 8 * stack_idx);
                    em.w(&format!("    {}", load_insn(ty, &src)));
                    em.store_vreg(dst.0, ty);
                }
            }
        }
        Inst::Phi { .. } => {
            // Phis are lowered to edge copies by SSA destruction before
            // codegen; reaching this point is an internal invariant violation,
            // so abort loudly instead of emitting wrong code.
            em.w("    ud2 # phi reached codegen (internal invariant violated)");
        }
    }
}

// CEP:WHAT: Handles the emit const step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_const(em: &mut FuncEmitter, dst: planck_ir::Vreg, value: &Const) {
    match value {
        Const::Int(v, ty) => {
            let width = width_of(ty);
            let imm = *v;
            let fits32 = imm >= i32::MIN as i128 && imm <= i32::MAX as i128;
            if width == 8 && !fits32 {
                em.w(&format!("    movabsq ${}, %rax", imm));
            } else {
                let suffix = int_suffix(width);
                let reg = match width {
                    1 => "%al",
                    2 => "%ax",
                    4 => "%eax",
                    _ => "%rax",
                };
                em.w(&format!("    mov{} ${}, {}", suffix, imm, reg));
            }
            em.store_vreg(dst.0, ty);
        }
        Const::Float(v, is_f32) => {
            let bits = if *is_f32 {
                (*v as f32).to_bits() as u64
            } else {
                v.to_bits()
            };
            let label = em
                .float_pool
                .get(&(*is_f32, bits))
                .cloned()
                .unwrap_or_else(|| "Lflt_unknown".to_string());
            let suffix = if *is_f32 { "ss" } else { "sd" };
            em.w(&format!("    mov{} {}(%rip), %xmm0", suffix, label));
            let ty = if *is_f32 { Ty::F32 } else { Ty::F64 };
            em.store_vreg(dst.0, &ty);
        }
        Const::Bool(v) => {
            em.w(&format!("    movb ${}, %al", if *v { 1 } else { 0 }));
            em.store_vreg(dst.0, &Ty::Bool);
        }
        Const::Char(c) => {
            em.w(&format!("    movl ${}, %eax", *c as u32));
            em.store_vreg(dst.0, &Ty::Char);
        }
        Const::Str(id) => {
            let label = em
                .program
                .rodata
                .get(*id as usize)
                .map(|entry| entry.label.clone())
                .unwrap_or_else(|| "Lstr_invalid".to_string());
            em.w(&format!("    lea {}(%rip), %rax", label));
            em.store_vreg(dst.0, &Ty::U64);
        }
    }
}

// CEP:WHAT: Handles the emit bin step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_bin(
    em: &mut FuncEmitter,
    op: BinOp,
    dst: planck_ir::Vreg,
    a: planck_ir::Vreg,
    b: planck_ir::Vreg,
    ty: &Ty,
    checked: bool,
) {
    let width = width_of(ty);
    let suffix = int_suffix(width);
    if ty.is_float() {
        if op.is_comparison() {
            emit_float_cmp(em, op, dst, a, b, ty);
        } else {
            emit_float_bin(em, op, dst, a, b, ty);
        }
        return;
    }
    if op.is_comparison() {
        emit_cmp(em, op, dst, a, b, ty);
        return;
    }
    // Integer operations: a lands in %rax (widened), b in %rcx (widened); narrow
    // operation suffixes act on the low bits, which is exactly the truncation semantics.
    em.load_vreg(a.0, ty);
    em.w("    movq %rax, %r10");
    em.load_vreg(b.0, ty);
    em.w("    movq %rax, %rcx");
    em.w("    movq %r10, %rax");
    let (creg, areg) = narrow_regs(suffix);
    match op {
        BinOp::Add => {
            em.w(&format!("    add{} {}, {}", suffix, creg, areg));
            if checked {
                let flag = if ty.is_signed() { "jo" } else { "jc" };
                em.w(&format!(
                    "    {} {}_{}",
                    flag,
                    trap_label(TrapKind::Overflow),
                    em.fn_index
                ));
            }
        }
        BinOp::Sub => {
            em.w(&format!("    sub{} {}, {}", suffix, creg, areg));
            if checked {
                let flag = if ty.is_signed() { "jo" } else { "jc" };
                em.w(&format!(
                    "    {} {}_{}",
                    flag,
                    trap_label(TrapKind::Overflow),
                    em.fn_index
                ));
            }
        }
        BinOp::Mul => {
            emit_mul(em, dst, a, ty, checked);
            return;
        }
        BinOp::Div | BinOp::Rem => {
            emit_div(em, op, dst, a, ty, checked);
            return;
        }
        BinOp::BitAnd => em.w(&format!("    and{} {}, {}", suffix, creg, areg)),
        BinOp::BitOr => em.w(&format!("    or{} {}, {}", suffix, creg, areg)),
        BinOp::BitXor => em.w(&format!("    xor{} {}, {}", suffix, creg, areg)),
        BinOp::Shl => em.w(&format!("    shl{} {}, {}", suffix, creg, areg)),
        BinOp::Shr => {
            let insn = if ty.is_signed() { "sar" } else { "shr" };
            em.w(&format!("    {}{} {}, {}", insn, suffix, creg, areg));
        }
        BinOp::Eq | BinOp::Ne | BinOp::Lt | BinOp::Le | BinOp::Gt | BinOp::Ge => {
            unreachable!("handled by emit_cmp")
        }
    }
    // The result sits in the low bits of rax; widen per type before storing.
    match ty {
        Ty::I8 => em.w("    movsbq %al, %rax"),
        Ty::U8 | Ty::Bool => em.w("    movzbq %al, %rax"),
        Ty::I16 => em.w("    movswq %ax, %rax"),
        Ty::U16 => em.w("    movzwq %ax, %rax"),
        _ => {}
    }
    em.store_vreg(dst.0, ty);
}

/// Register pair for narrow-width operations at the given AT&T suffix.
fn narrow_regs(suffix: &str) -> (&'static str, &'static str) {
    match suffix {
        "b" => ("%cl", "%al"),
        "w" => ("%cx", "%ax"),
        "l" => ("%ecx", "%eax"),
        _ => ("%rcx", "%rax"),
    }
}

/// Loads `a` back into %rax before an operation that clobbers it (used by div/mul paths).
// CEP:WHAT: Handles the reload operand step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn reload_operand(em: &mut FuncEmitter, vreg: planck_ir::Vreg, ty: &Ty) {
    em.forwarded = None;
    em.load_vreg(vreg.0, ty);
}

// CEP:WHAT: Handles the emit mul step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_mul(
    em: &mut FuncEmitter,
    dst: planck_ir::Vreg,
    a: planck_ir::Vreg,
    ty: &Ty,
    checked: bool,
) {
    let width = width_of(ty);
    match width {
        8 => {
            reload_operand(em, a, ty);
            // b is in %rcx from the caller.
            em.w("    imulq %rcx, %rax");
            if checked {
                let flag = if ty.is_signed() { "jo" } else { "jc" };
                em.w(&format!(
                    "    {} {}_{}",
                    flag,
                    trap_label(TrapKind::Overflow),
                    em.fn_index
                ));
            }
        }
        4 => {
            reload_operand(em, a, ty);
            em.w("    imull %ecx, %eax");
            if checked {
                let flag = if ty.is_signed() { "jo" } else { "jc" };
                em.w(&format!(
                    "    {} {}_{}",
                    flag,
                    trap_label(TrapKind::Overflow),
                    em.fn_index
                ));
            }
            if ty.is_signed() {
                em.w("    movslq %eax, %rax");
            } else {
                em.w("    movl %eax, %eax");
            }
        }
        // 1- and 2-byte multiplies: the 32-bit product of two narrow values is exact,
        // so checked overflow is a range compare; unchecked wraps by narrow store.
        _ => {
            reload_operand(em, a, ty);
            // Sign/zero-extend a into 32 bits.
            if ty.is_signed() {
                em.w("    movswl %ax, %eax");
            } else {
                em.w("    movzwl %ax, %eax");
            }
            em.w("    movl %eax, %r10d");
            // b (sign/zero-extended in rcx low bits) into 32 bits.
            if ty.is_signed() {
                em.w("    movswl %cx, %ecx");
            } else {
                em.w("    movzwl %cx, %ecx");
            }
            em.w("    imull %ecx, %r10d");
            if checked {
                let (lo, hi) = if ty.is_signed() {
                    (-(1i128 << (width * 8 - 1)), (1i128 << (width * 8 - 1)) - 1)
                } else {
                    (0, (1i128 << (width * 8)) - 1)
                };
                em.w(&format!("    cmpq ${}, %r10", lo));
                em.w(&format!(
                    "    jl {}_{}",
                    trap_label(TrapKind::Overflow),
                    em.fn_index
                ));
                em.w(&format!("    cmpq ${}, %r10", hi));
                em.w(&format!(
                    "    jg {}_{}",
                    trap_label(TrapKind::Overflow),
                    em.fn_index
                ));
            }
            em.w("    movl %r10d, %eax");
        }
    }
    em.store_vreg(dst.0, ty);
}

// CEP:WHAT: Handles the emit div step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_div(
    em: &mut FuncEmitter,
    op: BinOp,
    dst: planck_ir::Vreg,
    a: planck_ir::Vreg,
    ty: &Ty,
    _checked: bool,
) {
    let width = width_of(ty);
    let _ = suffix_label(width);
    // At this point %rcx holds b (widened) and %r10 holds a (widened) from the caller.
    if ty.is_signed() {
        // Guard the MinInt / -1 hardware fault with an explicit overflow trap.
        em.w("    cmpq $-1, %rcx");
        em.w(&format!("    jne Ldiv_ok_{}", em.fn_index));
        let min = -(1i128 << (width * 8 - 1));
        if min < i32::MIN as i128 {
            // The immediate does not fit the signed 32-bit compare form; route it
            // through a register (rax is free here: a is parked in r10).
            em.w(&format!("    movabsq ${}, %rax", min));
            em.w("    cmpq %rax, %r10");
        } else {
            em.w(&format!("    cmpq ${}, %r10", min));
        }
        em.w(&format!(
            "    je {}_{}",
            trap_label(TrapKind::Overflow),
            em.fn_index
        ));
        em.w(&format!("Ldiv_ok_{}:", em.fn_index));
        reload_operand(em, a, ty);
        match width {
            8 => {
                em.w("    cqto");
                em.w("    idivq %rcx");
            }
            4 => {
                em.w("    cltd");
                em.w("    idivl %ecx");
            }
            2 => {
                em.w("    cwtd");
                em.w("    idivw %cx");
            }
            _ => {
                em.w("    cbtw");
                em.w("    idivb %cl");
            }
        }
    } else {
        // Unsigned division: zero-extend into rdx, then div.
        reload_operand(em, a, ty);
        match width {
            8 => {
                em.w("    xorl %edx, %edx");
                em.w("    divq %rcx");
            }
            4 => {
                em.w("    xorl %edx, %edx");
                em.w("    divl %ecx");
            }
            2 => {
                em.w("    xorl %edx, %edx");
                em.w("    divw %cx");
            }
            _ => {
                em.w("    xorb %ah, %ah");
                em.w("    divb %cl");
            }
        }
    }
    if op == BinOp::Rem {
        em.w("    movq %rdx, %rax");
    }
    match ty {
        Ty::I8 => em.w("    movsbq %al, %rax"),
        Ty::U8 | Ty::Bool => em.w("    movzbq %al, %rax"),
        Ty::I16 => em.w("    movswq %ax, %rax"),
        Ty::U16 => em.w("    movzwq %ax, %rax"),
        _ => {}
    }
    em.store_vreg(dst.0, ty);
}

fn suffix_label(_width: u32) -> &'static str {
    "q"
}

// CEP:WHAT: Handles the emit cmp step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_cmp(
    em: &mut FuncEmitter,
    op: BinOp,
    dst: planck_ir::Vreg,
    a: planck_ir::Vreg,
    b: planck_ir::Vreg,
    ty: &Ty,
) {
    if ty.is_float() {
        emit_float_cmp(em, op, dst, a, b, ty);
        return;
    }
    let suffix = int_suffix(width_of(ty));
    em.load_vreg(a.0, ty);
    em.w("    movq %rax, %r10");
    em.load_vreg(b.0, ty);
    em.w("    movq %rax, %rcx");
    em.w("    movq %r10, %rax");
    let (creg, areg) = narrow_regs(suffix);
    em.w(&format!("    cmp{} {}, {}", suffix, creg, areg));
    let set = match (op, ty.is_signed()) {
        (BinOp::Eq, _) => "sete",
        (BinOp::Ne, _) => "setne",
        (BinOp::Lt, true) | (BinOp::Lt, false) if ty.is_signed() => "setl",
        (BinOp::Lt, false) => "setb",
        (BinOp::Le, true) => "setle",
        (BinOp::Le, false) => "setbe",
        (BinOp::Gt, true) => "setg",
        (BinOp::Gt, false) => "seta",
        (BinOp::Ge, true) => "setge",
        (BinOp::Ge, false) => "setae",
        _ => "sete",
    };
    em.w(&format!("    {} %al", set));
    em.w("    movzbq %al, %rax");
    em.store_vreg(dst.0, &Ty::Bool);
}

// CEP:WHAT: Handles the emit float bin step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_float_bin(
    em: &mut FuncEmitter,
    op: BinOp,
    dst: planck_ir::Vreg,
    a: planck_ir::Vreg,
    b: planck_ir::Vreg,
    ty: &Ty,
) {
    let suffix = if matches!(ty, Ty::F32) { "ss" } else { "sd" };
    let b_reg = "%xmm1";
    em.load_vreg(a.0, ty);
    em.w(&format!("    mov{} %xmm0, %xmm2", suffix));
    em.load_vreg(b.0, ty);
    em.w(&format!("    mov{} %xmm0, {}", suffix, b_reg));
    em.w(&format!("    mov{} %xmm2, %xmm0", suffix));
    let insn = match op {
        BinOp::Add => format!("add{}", suffix),
        BinOp::Sub => format!("sub{}", suffix),
        BinOp::Mul => format!("mul{}", suffix),
        BinOp::Div => format!("div{}", suffix),
        _ => {
            // Comparison handled separately.
            let _ = dst;
            return;
        }
    };
    em.w(&format!("    {} {}, %xmm0", insn, b_reg));
    em.store_vreg(dst.0, ty);
}

// CEP:WHAT: Handles the emit float cmp step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_float_cmp(
    em: &mut FuncEmitter,
    op: BinOp,
    dst: planck_ir::Vreg,
    a: planck_ir::Vreg,
    b: planck_ir::Vreg,
    ty: &Ty,
) {
    let suffix = if matches!(ty, Ty::F32) { "ss" } else { "sd" };
    em.load_vreg(a.0, ty);
    em.w(&format!("    mov{} %xmm0, %xmm2", suffix));
    em.load_vreg(b.0, ty);
    // Operand order: a lands in %xmm2, b in %xmm0. AT&T `ucomis src, dst`
    // maps to Intel UCOMISD dst, src, so `ucomis %xmm0, %xmm2` compares
    // %xmm2 (a) against %xmm0 (b) and the flags reflect `a OP b`.
    em.w(&format!("    ucomi{} %xmm0, %xmm2", suffix));
    // Flags: setcc below selects on `a OP b` directly.
    let set = match op {
        BinOp::Eq => "sete",
        BinOp::Ne => "setne",
        BinOp::Lt => "setb",
        BinOp::Le => "setbe",
        BinOp::Gt => "seta",
        BinOp::Ge => "setae",
        _ => "sete",
    };
    if matches!(op, BinOp::Ne) {
        // NaN != x is true: unordered (PF=1) counts as not-equal.
        em.w("    setne %al");
        em.w("    setp %cl");
        em.w("    orb %cl, %al");
    } else {
        // Equality/ordering: false when unordered (PF set).
        em.w(&format!("    {} %al", set));
        em.w("    setnp %cl");
        em.w("    andb %cl, %al");
    }
    em.w("    movzbq %al, %rax");
    em.store_vreg(dst.0, &Ty::Bool);
}

// CEP:WHAT: Handles the emit unary step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_unary(
    em: &mut FuncEmitter,
    op: UnOp,
    dst: planck_ir::Vreg,
    a: planck_ir::Vreg,
    ty: &Ty,
    checked: bool,
) {
    match (op, ty) {
        (UnOp::Neg, t) if t.is_float() => {
            let suffix = if matches!(t, Ty::F32) { "ss" } else { "sd" };
            em.load_vreg(a.0, t);
            em.w("    xorps %xmm1, %xmm1");
            em.w(&format!("    sub{} %xmm0, %xmm1", suffix));
            em.w(&format!("    mov{} %xmm1, %xmm0", suffix));
            em.store_vreg(dst.0, t);
        }
        (UnOp::Neg, t) => {
            let suffix = int_suffix(width_of(t));
            let (_, areg) = narrow_regs(suffix);
            em.load_vreg(a.0, t);
            em.w(&format!("    neg{} {}", suffix, areg));
            if checked {
                em.w(&format!(
                    "    jo {}_{}",
                    trap_label(TrapKind::Overflow),
                    em.fn_index
                ));
            }
            match ty {
                Ty::I8 => em.w("    movsbq %al, %rax"),
                Ty::I16 => em.w("    movswq %ax, %rax"),
                Ty::I32 => em.w("    movslq %eax, %rax"),
                _ => {}
            }
            em.store_vreg(dst.0, t);
        }
        (UnOp::Not, Ty::Bool) => {
            em.load_vreg(a.0, ty);
            em.w("    xorb $1, %al");
            em.w("    movzbq %al, %rax");
            em.store_vreg(dst.0, ty);
        }
        (UnOp::Not, t) => {
            let suffix = int_suffix(width_of(t));
            let (_, areg) = narrow_regs(suffix);
            em.load_vreg(a.0, t);
            em.w(&format!("    not{} {}", suffix, areg));
            match ty {
                Ty::I8 => em.w("    movsbq %al, %rax"),
                Ty::U8 => em.w("    movzbq %al, %rax"),
                Ty::I16 => em.w("    movswq %ax, %rax"),
                Ty::U16 => em.w("    movzwq %ax, %rax"),
                _ => {}
            }
            em.store_vreg(dst.0, t);
        }
    }
}

// CEP:WHAT: Handles the emit cast step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_cast(em: &mut FuncEmitter, dst: planck_ir::Vreg, src: planck_ir::Vreg, from: &Ty, to: &Ty) {
    // Integer -> integer: load with FROM widening, store with TO width (truncates).
    if from.is_integer() && to.is_integer() {
        em.load_vreg(src.0, from);
        em.store_vreg(dst.0, to);
        return;
    }
    if from.is_integer() && to.is_float() {
        em.load_vreg(src.0, from);
        // u64 >= 2^63 uses the signed conversion (documented deviation, ticket PLK-023).
        if matches!(to, Ty::F32) {
            em.w("    cvtsi2ssq %rax, %xmm0");
        } else {
            em.w("    cvtsi2sdq %rax, %xmm0");
        }
        em.store_vreg(dst.0, to);
        return;
    }
    if from.is_float() && to.is_integer() {
        em.load_vreg(src.0, from);
        // Truncation with hardware semantics; out-of-range yields the hardware sentinel
        // truncated to the destination width (ticket PLK-023).
        if matches!(from, Ty::F32) {
            em.w("    cvttss2si %xmm0, %rax");
        } else {
            em.w("    cvttsd2si %xmm0, %rax");
        }
        em.store_vreg(dst.0, to);
        return;
    }
    if from.is_float() && to.is_float() {
        em.load_vreg(src.0, from);
        if matches!(to, Ty::F64) {
            em.w("    cvtss2sd %xmm0, %xmm0");
        } else {
            em.w("    cvtsd2ss %xmm0, %xmm0");
        }
        em.store_vreg(dst.0, to);
        return;
    }
    // char -> int / int -> char behave as integer casts of the 4-byte representation.
    em.load_vreg(src.0, from);
    em.store_vreg(dst.0, to);
}

// CEP:WHAT: Handles the emit call step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_call(
    em: &mut FuncEmitter,
    dst: Option<planck_ir::Vreg>,
    sret: Option<planck_ir::Vreg>,
    callee: Callee,
    args: &[planck_ir::CallArg],
    ret: &Ty,
) {
    // Classify arguments into integer-register, float-register, and stack classes.
    let int_regs = ["%rdi", "%rsi", "%rdx", "%rcx", "%r8", "%r9"];
    let mut int_args: Vec<(u32, Ty)> = Vec::new();
    let mut float_args: Vec<(u32, Ty)> = Vec::new();
    for arg in args {
        match &arg.ty {
            Ty::F32 | Ty::F64 => float_args.push((arg.value.0, arg.ty.clone())),
            _ => int_args.push((arg.value.0, arg.ty.clone())),
        }
    }
    let _ = &int_args;
    let hidden_sret = sret.is_some();
    // Stack args beyond six integer registers.
    let total_int = int_args.len() + usize::from(hidden_sret);
    let stack_args = total_int.saturating_sub(int_regs.len());
    let pad = stack_args % 2;
    if pad > 0 {
        em.w(&format!("    subq ${}, %rsp", pad * 8));
    }
    // Push stack args in reverse order.
    let mut stack_written = 0usize;
    for idx in (0..int_args.len()).rev() {
        let reg_slot = idx + usize::from(hidden_sret);
        if reg_slot >= int_regs.len() {
            let (vreg, _ty) = &int_args[idx];
            em.load_vreg(*vreg, &Ty::U64);
            em.w("    pushq %rax");
            stack_written += 1;
        }
    }
    // Float args.
    for (xmm_idx, (vreg, ty)) in float_args.iter().enumerate() {
        em.load_vreg(*vreg, ty);
        if xmm_idx < 8 {
            em.w(&format!(
                "    mov{} %xmm0, %xmm{}",
                if matches!(ty, Ty::F32) { "ss" } else { "sd" },
                xmm_idx
            ));
        } else {
            // More than eight float arguments are not supported in this milestone
            // (documented limitation; the verifier does not reject them).
            em.w("    ; unsupported: float stack argument dropped (PLK-026)");
        }
    }
    // Integer args + hidden sret.
    if let Some(sret_vreg) = sret {
        em.load_vreg(sret_vreg.0, &Ty::U64);
        em.w("    movq %rax, %rdi");
    }
    for (idx, (vreg, ty)) in int_args.iter().enumerate() {
        let reg_slot = idx + usize::from(hidden_sret);
        if reg_slot < int_regs.len() {
            // load_insn widens every type to 64 bits using the SOURCE width, so narrow
            // slot reads never pull in neighboring bytes.
            em.load_vreg(*vreg, ty);
            em.w(&format!("    movq %rax, {}", int_regs[reg_slot]));
        }
    }
    // Symbol.
    let symbol = match callee {
        Callee::Func(id) => symbol_name(&em.program.funcs[id.0 as usize].name),
        Callee::Intrinsic(kind) => match (kind, args.first().map(|a| &a.ty)) {
            (Intrinsic::PrintStr, _) => "planck_rt_print_str".to_string(),
            (Intrinsic::Print, Some(Ty::F64)) | (Intrinsic::Print, Some(Ty::F32)) => {
                "planck_rt_print_f64".to_string()
            }
            (Intrinsic::Print, Some(ty)) if ty.is_signed() => "planck_rt_print_i64".to_string(),
            (Intrinsic::Print, Some(ty)) if ty.is_integer() => "planck_rt_print_u64".to_string(),
            (Intrinsic::Print, Some(Ty::Bool)) => "planck_rt_print_bool".to_string(),
            (Intrinsic::Print, Some(Ty::Char)) => "planck_rt_print_char".to_string(),
            (Intrinsic::Print, _) => "planck_rt_print_i64".to_string(),
            (Intrinsic::Panic, _) => "planck_rt_panic".to_string(),
        },
    };
    em.invalidate_forward();
    em.w(&format!("    call {}", symbol));
    if stack_written > 0 || pad > 0 {
        em.w(&format!("    addq ${}, %rsp", (stack_written + pad) * 8));
    }
    // Result.
    if let Some(dst_vreg) = dst {
        match ret {
            Ty::F32 | Ty::F64 => {
                em.store_vreg(dst_vreg.0, ret);
            }
            _ => {
                em.store_vreg(dst_vreg.0, ret);
            }
        }
    }
}

// A small extension so emit_inst can query aggregate sizes without a second table.
trait SizeQuery {
    fn tables_size_of(&self, ty: &Ty) -> u32;
}

impl<'a> SizeQuery for FuncEmitter<'a> {
    fn tables_size_of(&self, ty: &Ty) -> u32 {
        match ty {
            Ty::Struct(id) => self.program.structs[id.0 as usize].size,
            Ty::Enum(id) => self.program.enums[id.0 as usize].size,
            Ty::Array(elem, n) => elem.scalar_size().unwrap_or(8).saturating_mul(*n as u32),
            other => other.scalar_size().unwrap_or(8),
        }
    }
}
