/// Emits the complete assembly file: text section, read-only data, and every function.
// CEP:WHAT: Handles the emit assembly step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
pub fn emit_assembly(program: &Program) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# generated by planckc {} — deterministic output",
        planck_ir::IR_FORMAT_VERSION
    );
    let _ = writeln!(out, "    .text");

    // Float literal pool (deduplicated by bit pattern, ordered for determinism).
    let mut float_pool: BTreeMap<(bool, u64), String> = BTreeMap::new();
    let float_count = {
        let mut count = 0usize;
        for func in &program.funcs {
            for block in &func.blocks {
                for inst in &block.insts {
                    if let Inst::Const {
                        value: Const::Float(value, is_f32),
                        ..
                    } = inst
                    {
                        let bits = if *is_f32 {
                            (*value as f32).to_bits() as u64
                        } else {
                            value.to_bits()
                        };
                        if float_pool
                            .insert((*is_f32, bits), format!("Lflt_{}", count))
                            .is_none()
                        {
                            count += 1;
                        }
                    }
                }
            }
        }
        count
    };
    let _ = float_count;

    for (idx, func) in program.funcs.iter().enumerate() {
        emit_func(&mut out, program, func, idx, &float_pool);
    }

    // Read-only data.
    let _ = writeln!(out, "    .section .rodata");
    for entry in &program.rodata {
        let _ = writeln!(out, "    .align 1");
        let _ = writeln!(out, "{}:", entry.label);
        let mut line = String::from("    .byte ");
        for (i, byte) in entry.bytes.iter().enumerate() {
            if i > 0 {
                line.push(',');
            }
            let _ = write!(line, "{}", byte);
        }
        if entry.bytes.is_empty() {
            line.push('0');
        }
        let _ = writeln!(out, "{}", line);
    }
    for ((is_f32, bits), label) in &float_pool {
        let _ = writeln!(out, "    .align {}", if *is_f32 { 4 } else { 8 });
        let _ = writeln!(out, "{}:", label);
        if *is_f32 {
            let _ = writeln!(out, "    .long {}", *bits as u32);
        } else {
            let _ = writeln!(out, "    .quad {}", bits);
        }
    }
    // Trap messages.
    for (kind, message) in trap_messages() {
        let _ = writeln!(out, "    .align 1");
        let _ = writeln!(out, "{}:", trap_label(kind));
        let _ = writeln!(out, "    .ascii \"{}\"", message);
        let _ = writeln!(out, "    .byte 0");
    }
    out
}

fn trap_messages() -> Vec<(TrapKind, &'static str)> {
    vec![
        (TrapKind::Overflow, "arithmetic overflow"),
        (TrapKind::Bounds, "index out of bounds"),
        (TrapKind::DivZero, "division by zero"),
        (TrapKind::Panic, "explicit panic"),
    ]
}

fn trap_label(kind: TrapKind) -> String {
    format!("Ltrap_{}", trap_kind_name(kind))
}

fn trap_kind_name(kind: TrapKind) -> &'static str {
    match kind {
        TrapKind::Overflow => "overflow",
        TrapKind::Bounds => "bounds",
        TrapKind::DivZero => "divzero",
        TrapKind::Panic => "panic",
    }
}

fn symbol_name(name: &str) -> String {
    if name == "main" {
        return "planck_main".to_string();
    }
    format!("plk_{}", name.replace("::", "_"))
}

struct FuncEmitter<'a> {
    out: String,
    program: &'a Program,
    func: &'a IrFunc,
    fn_index: usize,
    frame: Frame,
    /// Vreg currently resident in %rax for load elision.
    forwarded: Option<u32>,
    float_pool: &'a BTreeMap<(bool, u64), String>,
}

impl<'a> FuncEmitter<'a> {
    fn new(
        program: &'a Program,
        func: &'a IrFunc,
        fn_index: usize,
        float_pool: &'a BTreeMap<(bool, u64), String>,
    ) -> Self {
        FuncEmitter {
            out: String::new(),
            program,
            func,
            fn_index,
            frame: frame::compute(func),
            forwarded: None,
            float_pool,
        }
    }

    // CEP:WHAT: Handles the w step of this stage per the design and the file header contract.
    // CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
    // CEP:STATUS: complete
    // CEP:FAILURE: Returns diagnostics or results; never panics on any input.
    // CEP:ASSUMES: See the file header for the stage-wide assumptions.
    // CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
    // CEP:EVIDENCE: cargo test over the containing crate.
    fn w(&mut self, line: &str) {
        self.out.push_str(line);
        self.out.push('\n');
    }

    fn block_label(&self, block: u32) -> String {
        format!("Lf{}_b{}", self.fn_index, block)
    }

    fn vreg_mem(&self, vreg: u32) -> String {
        format!("-{}(%rbp)", self.frame.vreg_offset(vreg))
    }

    // CEP:WHAT: Handles the slot mem step of this stage per the design and the file header contract.
    // CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
    // CEP:STATUS: complete
    // CEP:FAILURE: Returns diagnostics or results; never panics on any input.
    // CEP:ASSUMES: See the file header for the stage-wide assumptions.
    // CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
    // CEP:EVIDENCE: cargo test over the containing crate.
    fn slot_mem(&self, slot: planck_ir::Slot, offset: u32) -> String {
        let base = self.frame.slot_offset(slot);
        let total = base.saturating_sub(offset);
        format!("-{}(%rbp)", total)
    }

    fn invalidate_forward(&mut self) {
        self.forwarded = None;
    }

    /// Loads a value into %rax, reusing the forwarded copy when possible.
    // CEP:WHAT: Handles the load vreg step of this stage per the design and the file header contract.
    // CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
    // CEP:STATUS: complete
    // CEP:FAILURE: Returns diagnostics or results; never panics on any input.
    // CEP:ASSUMES: See the file header for the stage-wide assumptions.
    // CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
    // CEP:EVIDENCE: cargo test over the containing crate.
    fn load_vreg(&mut self, vreg: u32, ty: &Ty) {
        if self.forwarded == Some(vreg) {
            return;
        }
        let mem = self.vreg_mem(vreg);
        self.w(&format!("    {}", load_insn(ty, &mem)));
        self.forwarded = Some(vreg);
    }

    /// Stores %rax (or %xmm0 for floats) into a vreg slot, then re-widens %rax so the
    /// forwarding invariant (rax holds the canonical widened value) stays true: without
    /// this, a narrow store leaves stale high bits that a forwarded reload would reuse.
    // CEP:WHAT: Handles the store vreg step of this stage per the design and the file header contract.
    // CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
    // CEP:STATUS: complete
    // CEP:FAILURE: Returns diagnostics or results; never panics on any input.
    // CEP:ASSUMES: See the file header for the stage-wide assumptions.
    // CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
    // CEP:EVIDENCE: cargo test over the containing crate.
    fn store_vreg(&mut self, vreg: u32, ty: &Ty) {
        let mem = self.vreg_mem(vreg);
        self.w(&format!("    {}", store_insn(ty, &mem)));
        match ty {
            Ty::I8 => self.w("    movsbq %al, %rax"),
            Ty::U8 | Ty::Bool => self.w("    movzbq %al, %rax"),
            Ty::I16 => self.w("    movswq %ax, %rax"),
            Ty::U16 => self.w("    movzwq %ax, %rax"),
            Ty::I32 => self.w("    movslq %eax, %rax"),
            Ty::U32 | Ty::Char => self.w("    movl %eax, %eax"),
            _ => {}
        }
        self.forwarded = Some(vreg);
    }
}

fn int_suffix(width: u32) -> &'static str {
    match width {
        1 => "b",
        2 => "w",
        4 => "l",
        _ => "q",
    }
}

fn width_of(ty: &Ty) -> u32 {
    ty.scalar_size().unwrap_or(8)
}

/// Load instruction that widens to 64-bit %rax per source type.
fn load_insn(ty: &Ty, mem: &str) -> String {
    match ty {
        Ty::I8 => format!("movsbq {}, %rax", mem),
        Ty::I16 => format!("movswq {}, %rax", mem),
        Ty::I32 => format!("movslq {}, %rax", mem),
        Ty::U8 | Ty::Bool => format!("movzbq {}, %rax", mem),
        Ty::U16 => format!("movzwq {}, %rax", mem),
        Ty::U32 | Ty::Char => format!("movl {}, %eax", mem),
        Ty::F32 => format!("movss {}, %xmm0", mem),
        Ty::F64 => format!("movsd {}, %xmm0", mem),
        _ => format!("movq {}, %rax", mem),
    }
}

/// Store instruction writing the low bits of %rax (or %xmm0) to memory.
fn store_insn(ty: &Ty, mem: &str) -> String {
    match ty {
        Ty::I8 | Ty::U8 | Ty::Bool => format!("movb %al, {}", mem),
        Ty::I16 | Ty::U16 => format!("movw %ax, {}", mem),
        Ty::I32 | Ty::U32 | Ty::Char => format!("movl %eax, {}", mem),
        Ty::F32 => format!("movss %xmm0, {}", mem),
        Ty::F64 => format!("movsd %xmm0, {}", mem),
        _ => format!("movq %rax, {}", mem),
    }
}

// CEP:WHAT: Handles the emit func step of this stage per the design and the file header contract.
// CEP:WHY: The stage's contract requires this step; the module documentation records the design choice and rejected alternatives.
// CEP:STATUS: complete
// CEP:FAILURE: Returns diagnostics or results; never panics on any input.
// CEP:ASSUMES: See the file header for the stage-wide assumptions.
// CEP:COST: Bounded by the input size of this stage; no allocation beyond the documented model.
// CEP:EVIDENCE: cargo test over the containing crate.
fn emit_func(
    out: &mut String,
    program: &Program,
    func: &IrFunc,
    fn_index: usize,
    float_pool: &BTreeMap<(bool, u64), String>,
) {
    let mut em = FuncEmitter::new(program, func, fn_index, float_pool);
    let symbol = symbol_name(&func.name);

    let _ = writeln!(em.out, "    .globl {}", symbol);
    let _ = writeln!(em.out, "    .type {}, @function", symbol);
    let _ = writeln!(em.out, "{}:", symbol);
    // Prologue.
    em.w("    pushq %rbp");
    em.w("    movq %rsp, %rbp");
    em.w(&format!("    subq ${}, %rsp", em.frame.frame_size));
    // Save the hidden sret pointer before anything can clobber rdi.
    if let (Some(_), Some(save_off)) = (func.sret_slot, em.frame.sret_save_offset) {
        em.w(&format!("    movq %rdi, -{}(%rbp)", save_off));
    }
    // Spill parameters from their ABI registers into frame slots. Parameters
    // that the SSA stage promoted are read by their Arg instruction instead.
    let promoted_params: std::collections::BTreeSet<u32> = func
        .blocks
        .first()
        .map(|entry| {
            entry
                .insts
                .iter()
                .filter_map(|inst| match inst {
                    Inst::Arg { index, .. } => Some(*index),
                    _ => None,
                })
                .collect()
        })
        .unwrap_or_default();
    emit_param_spills(&mut em, &promoted_params);

    for (block_idx, block) in func.blocks.iter().enumerate() {
        let _ = writeln!(em.out, "{}:", em.block_label(block_idx as u32));
        em.forwarded = None; // conservative at block joins
        for inst in &block.insts {
            emit_inst(&mut em, inst);
        }
        match &block.term {
            Term::Br(target) => {
                let label = em.block_label(target.0);
                if label != em.block_label(block_idx as u32) {
                    em.w(&format!("    jmp {}", label));
                }
            }
            Term::BrCond {
                cond,
                then_blk,
                else_blk,
            } => {
                em.load_vreg(cond.0, &Ty::Bool);
                em.w("    testb $1, %al");
                em.w(&format!("    jne {}", em.block_label(then_blk.0)));
                em.w(&format!("    jmp {}", em.block_label(else_blk.0)));
            }
            Term::Ret { value } => {
                emit_return(&mut em, value.as_ref());
            }
        }
    }

    // Trap stubs.
    let mut used_kinds: Vec<TrapKind> = Vec::new();
    let record = |trap: TrapKind, used: &mut Vec<TrapKind>| {
        if !used.contains(&trap) {
            used.push(trap);
        }
    };
    for block in &func.blocks {
        for inst in &block.insts {
            match inst {
                Inst::TrapIf { trap, .. } | Inst::Trap { trap } => record(*trap, &mut used_kinds),
                // Checked arithmetic references the overflow stub directly.
                Inst::Bin {
                    checked,
                    ty,
                    op: _,
                    dst: _,
                    a: _,
                    b: _,
                } if *checked && ty.is_integer() => record(TrapKind::Overflow, &mut used_kinds),
                Inst::Un {
                    checked,
                    ty,
                    op,
                    dst: _,
                    a: _,
                } if *checked && ty.is_integer() && *op == UnOp::Neg => {
                    record(TrapKind::Overflow, &mut used_kinds)
                }
                // Signed division emits the MinInt / -1 guard, which branches to the
                // overflow stub directly.
                Inst::Bin {
                    op: bin_op,
                    ty,
                    checked: _,
                    dst: _,
                    a: _,
                    b: _,
                } if ty.is_signed() && bin_op.is_div_or_rem() => {
                    record(TrapKind::Overflow, &mut used_kinds)
                }
                _ => {}
            }
        }
    }
    used_kinds.sort_by_key(|k| match k {
        TrapKind::Overflow => 0,
        TrapKind::Bounds => 1,
        TrapKind::DivZero => 2,
        TrapKind::Panic => 3,
    });
    for kind in used_kinds {
        let _ = writeln!(em.out, "{}_{}:", trap_label(kind), fn_index);
        em.w(&format!("    lea {}(%rip), %rdi", trap_label(kind)));
        em.w("    call planck_rt_panic");
        em.w("    ud2");
    }
    let _ = writeln!(em.out, "    .size {}, .-{}", symbol, symbol);
    out.push_str(&em.out);
}

