#!/usr/bin/env python3
"""Deterministically generates the benchmark sources whose array initializers
are too large to hand-write.

Planck has no repeat-array expression (`[0; N]`): the grammar only offers
`ArrayLit` (doc/parser.md) and the definite-initialization checker is
whole-value granular (doc/sema.md), so a large array must be declared with a
full element list. The harness therefore generates those element lists here.

Outputs (committed, deterministic byte-for-byte):
  benches/sort.plk     -- bottom-up mergesort, [i32; 512] zero-initialized
  benches/matmul.plk   -- 48x48 i32 matrix multiply, three [i32; 2304] arrays
"""

import pathlib

HERE = pathlib.Path(__file__).resolve().parent


def fmt_literal(values, per_line):
    """Formats an array literal with `per_line` entries per line."""
    lines = []
    for start in range(0, len(values), per_line):
        chunk = values[start:start + per_line]
        lines.append("    " + ", ".join(str(v) for v in chunk) + ",")
    return "\n".join(lines).rstrip(",")


def gen_sort():
    n = 512
    zeros = fmt_literal([0] * n, 16)
    return f"""// Benchmark: bottom-up mergesort over xorshift-generated keys.
// Generated by benches/gen_sources.py -- do not edit by hand.
// Exercises: loops, i64 checked arithmetic, xorshift bit ops, index bounds
// checks, borrow passing, and the merge/copy memory traffic pattern.
fn fill(a: &mut [i32; {n}], seed: i64) -> () {{
    let mut x: i64 = seed;
    for i in 0..{n} {{
        x = x ^ (x << 13);
        x = x ^ (x >> 7);
        x = x ^ (x << 17);
        (*a)[i] = (x & 65535) as i32;
    }}
}}
fn min2(a: i32, b: i32) -> i32 {{
    if a < b {{ return a; }}
    return b;
}}
fn merge(a: &mut [i32; {n}], t: &mut [i32; {n}], lo: i32, mid: i32, hi: i32) -> () {{
    let mut i: i32 = lo;
    let mut j: i32 = mid;
    let mut k: i32 = lo;
    while i < mid && j < hi {{
        if (*a)[i] <= (*a)[j] {{
            (*t)[k] = (*a)[i];
            i = i + 1;
        }} else {{
            (*t)[k] = (*a)[j];
            j = j + 1;
        }}
        k = k + 1;
    }}
    while i < mid {{
        (*t)[k] = (*a)[i];
        i = i + 1;
        k = k + 1;
    }}
    while j < hi {{
        (*t)[k] = (*a)[j];
        j = j + 1;
        k = k + 1;
    }}
}}
fn copy_back(t: &mut [i32; {n}], a: &mut [i32; {n}]) -> () {{
    for i in 0..{n} {{
        (*a)[i] = (*t)[i];
    }}
}}
fn checksum(a: &[i32; {n}]) -> i64 {{
    let mut s: i64 = 0;
    for i in 0..{n} {{
        s = s + (*a)[i] as i64 * (i as i64 + 1);
    }}
    return s;
}}
fn main() -> i32 {{
    let mut data: [i32; {n}] = [
{zeros}
    ];
    let mut tmp: [i32; {n}] = [
{zeros}
    ];
    let mut total: i64 = 0;
    let base_seed: i64 = 88172645463325252;
    for r in 0..600 {{
        fill(&mut data, base_seed + r as i64);
        let mut width: i32 = 1;
        while width < {n} {{
            let mut lo: i32 = 0;
            while lo < {n} {{
                let mid: i32 = min2(lo + width, {n});
                let hi: i32 = min2(lo + 2 * width, {n});
                merge(&mut data, &mut tmp, lo, mid, hi);
                lo = lo + 2 * width;
            }}
            copy_back(&mut tmp, &mut data);
            width = width * 2;
        }}
        total = total + checksum(&data);
    }}
    print(total);
    print('\\n');
    return 0;
}}
"""


def gen_matmul():
    n = 48
    n2 = n * n
    zeros = fmt_literal([0] * n2, 16)
    return f"""// Benchmark: 48x48 i32 matrix multiply, {150} repetitions.
// Generated by benches/gen_sources.py -- do not edit by hand.
// Exercises: nested loops, flat index arithmetic, reference parameter
// dereference reads/writes, method-free struct access, checked i32 math.
struct Mat {{ d: [i32; {n2}] }}
fn fill(m: &mut Mat, seed: i64) -> () {{
    let mut x: i64 = seed;
    for i in 0..{n2} {{
        x = x ^ (x << 13);
        x = x ^ (x >> 7);
        x = x ^ (x << 17);
        (*m).d[i] = (x & 1023) as i32;
    }}
}}
fn mul(a: &Mat, b: &Mat, out: &mut Mat) -> () {{
    for i in 0..{n} {{
        for k in 0..{n} {{
            let av: i32 = (*a).d[i * {n} + k];
            for j in 0..{n} {{
                (*out).d[i * {n} + j] = (*out).d[i * {n} + j] + av * (*b).d[k * {n} + j];
            }}
        }}
    }}
}}
fn checksum(m: &Mat) -> i64 {{
    let mut s: i64 = 0;
    for i in 0..{n2} {{
        s = s + (*m).d[i] as i64 * (i as i64 + 1);
    }}
    return s;
}}
fn main() -> i32 {{
    let mut a: Mat = Mat {{ d: [
{zeros}
    ] }};
    let mut b: Mat = Mat {{ d: [
{zeros}
    ] }};
    let mut o: Mat = Mat {{ d: [
{zeros}
    ] }};
    let mut total: i64 = 0;
    let seed_a: i64 = 88172645463325252;
    let seed_b: i64 = 72057594037927936;
    for r in 0..150 {{
        fill(&mut a, seed_a + r as i64);
        fill(&mut b, seed_b + r as i64);
        fill(&mut o, 0);
        mul(&a, &b, &mut o);
        total = total + checksum(&o);
    }}
    print(total);
    print('\\n');
    return 0;
}}
"""


def main():
    (HERE / "sort.plk").write_text(gen_sort())
    (HERE / "matmul.plk").write_text(gen_matmul())
    print("generated benches/sort.plk, benches/matmul.plk")


if __name__ == "__main__":
    main()
